type PageCopyMap = {
  home: HomeCopy;
  contact: ContactCopy;
  services: ServicesCopy;
};

const PAGE_DATA = {
  home: homeJson as Record<string, HomeCopy>,
  contact: contactJson as Record<string, ContactCopy>,
  services: servicesJson as Record<string, ServicesCopy>,
} as const;

/**
 * Load page copy for a locale. Falls back to English for missing locales/keys.
 */
export function getPageCopy<K extends keyof PageCopyMap>(
  page: K,
  locale: Locale,
): PageCopyMap[K] {
  const data = PAGE_DATA[page];
  const en = data[DEFAULT_LOCALE] || data.en;
  const localized = data[locale];
  if (!localized) return en as PageCopyMap[K];
  if (locale === DEFAULT_LOCALE) return localized as PageCopyMap[K];
  return { ...en, ...localized } as PageCopyMap[K];
}
